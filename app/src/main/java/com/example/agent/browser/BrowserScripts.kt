package com.example.agent.browser

/**
 * JavaScript builders and result decoding for [WebViewBrowserEngine].
 *
 * Everything in here is deliberately free of Android imports: the engine only calls
 * `WebView.evaluateJavascript`, while *what* is executed and *how the answer is read* lives here
 * so it can be unit-tested on a plain JVM (see `BrowserScriptsTest`).
 *
 * **Result encoding.** Android serialises the value returned by `evaluateJavascript` as JSON, so
 * a script that returns the JavaScript string `'ok'` arrives at the callback as `"ok"` — with the
 * surrounding double quotes. Reading actions therefore go through [stripQuotes]; every action
 * script returns a short, quote-free token (`ok`, `not-found`, `occluded …`) so one unquote step
 * is enough. The page snapshot is an object, which serialises as a JSON object and is parsed
 * directly.
 *
 * **Injection safety.** Ref values are re-validated by [safeRef] inside every builder, and dynamic
 * values only ever reach the page through [jsStringLiteral]. A ref that fails validation produces
 * [INVALID_REF_SCRIPT], which returns a token instead of embedding anything into the script.
 */
internal object BrowserScripts {

    /** Refs are generated by the snapshot script (`agx-0`, `agx-1`, …); anything else is rejected. */
    private val REF_PATTERN = Regex("^[a-z0-9\\-]{1,24}$")

    /** Returned instead of a real script when the ref cannot be trusted. */
    private const val INVALID_REF_SCRIPT = "(function(){ return 'invalid-ref'; })()"

    /**
     * Normalises and validates a ref. Returns `null` when it cannot be used, in which case the
     * caller must report the error instead of running a script.
     */
    fun safeRef(ref: String): String? {
        val trimmed = ref.trim().lowercase()
        return if (REF_PATTERN.matches(trimmed)) trimmed else null
    }

    /**
     * Encodes [value] as a JavaScript string literal. Hand-rolled (instead of `org.json`, which is
     * only a stub in plain JVM tests) and safe against quote/backslash/newline injection.
     */
    fun jsStringLiteral(value: String): String = buildString(value.length + 2) {
        append('"')
        for (ch in value) {
            when (ch) {
                '"' -> append("\\\"")
                '\\' -> append("\\\\")
                '\n' -> append("\\n")
                '\r' -> append("\\r")
                '\t' -> append("\\t")
                '\u0008' -> append("\\b")
                '\u000C' -> append("\\f")
                '\u2028' -> append("\\u2028")
                '\u2029' -> append("\\u2029")
                else -> if (ch < ' ') {
                    append("\\u")
                    append(ch.code.toString(16).padStart(4, '0'))
                } else {
                    append(ch)
                }
            }
        }
        append('"')
    }

    /**
     * Undoes the JSON string encoding applied by `evaluateJavascript`.
     *
     * `"ok"` → `ok`, `ok` → `ok` (some WebView builds hand back the raw value), `null` → `null`,
     * and a Kotlin `null` stays `null`. Escape sequences are decoded so a payload containing a
     * quote survives the round-trip.
     */
    fun stripQuotes(raw: String?): String? {
        if (raw == null) return null
        val trimmed = raw.trim()
        if (trimmed == "null") return null
        if (trimmed.length < 2 || !trimmed.startsWith("\"") || !trimmed.endsWith("\"")) return trimmed
        val inner = trimmed.substring(1, trimmed.length - 1)
        val out = StringBuilder(inner.length)
        var i = 0
        while (i < inner.length) {
            val ch = inner[i]
            if (ch != '\\' || i == inner.length - 1) {
                out.append(ch)
                i++
                continue
            }
            when (val next = inner[i + 1]) {
                '"' -> { out.append('"'); i += 2 }
                '\\' -> { out.append('\\'); i += 2 }
                '/' -> { out.append('/'); i += 2 }
                'n' -> { out.append('\n'); i += 2 }
                'r' -> { out.append('\r'); i += 2 }
                't' -> { out.append('\t'); i += 2 }
                'b' -> { out.append('\b'); i += 2 }
                'f' -> { out.append('\u000C'); i += 2 }
                'u' -> {
                    val hex = inner.substring(i + 2, minOf(i + 6, inner.length))
                    val code = if (hex.length == 4) hex.toIntOrNull(16) else null
                    if (code != null) {
                        out.append(code.toChar())
                        i += 6
                    } else {
                        out.append(next)
                        i += 2
                    }
                }
                else -> { out.append(next); i += 2 }
            }
        }
        return out.toString()
    }

    /** True when the two fingerprints differ; an unavailable fingerprint never claims "no change". */
    fun changedBetween(before: String, after: String): Boolean {
        if (before.isEmpty() || after.isEmpty()) return true
        return before != after
    }

    /**
     * Turns a page-level failure token into an instruction the model can act on. Kept here (and
     * not inline in the engine) so the wording is testable.
     */
    fun describeToken(token: String, ref: String): String {
        val target = if (ref.isBlank()) "Elemen target" else "Elemen $ref"
        return when {
            token == "not-found" ->
                "$target sudah tidak ada di halaman (DOM berubah setelah aksi sebelumnya). " +
                    "Ambil snapshot baru dengan browser_read, lalu ulangi memakai ref yang baru."

            token == "disabled" -> "$target sedang nonaktif (disabled) di halaman."
            token == "readonly" -> "$target hanya-baca (readonly), jadi tidak bisa diisi."
            token == "invisible" -> "$target tidak terlihat (ukuran nol), jadi tidak bisa diaksi."
            token == "invalid-ref" -> "Ref elemen tidak valid: \"$ref\". Pakai ref dari browser_read."
            token.startsWith("occluded") ->
                "$target tertutup elemen lain di halaman ($token). Tutup overlay/modal lebih dulu " +
                    "(mis. browser_press_key Escape), ambil browser_read, lalu ulangi."

            token == "not-a-select" -> "$target bukan elemen <select>, jadi browser_select tidak berlaku."
            token == "option-not-found" -> "Opsi yang diminta tidak ada di <select> $target."
            token == "unsupported-key" ->
                "Tombol itu belum didukung. Pakai Enter, Escape, Tab, Backspace, Space, " +
                    "ArrowUp, ArrowDown, ArrowLeft, atau ArrowRight."

            token.startsWith("error") -> "Aksi gagal di halaman: $token"
            token.isBlank() -> "Aksi gagal di halaman (tidak ada jawaban dari halaman)."
            else -> "Aksi gagal di halaman ($token)."
        }
    }

