    /**
     * Clicks an element, but only after checking that it is still the thing on screen: present,
     * sized, enabled, and actually the topmost element at its own centre. That last check is what
     * stops a programmatic `click()` from firing a control that a modal or overlay has covered.
     */
    fun click(ref: String): String {
        val safe = safeRef(ref) ?: return INVALID_REF_SCRIPT
        return """
            (function(){
              try {
                var el = document.querySelector('[data-agx-ref="$safe"]');
                if (!el) return 'not-found';
                var r = el.getBoundingClientRect();
                if (r.width <= 0 || r.height <= 0) return 'invisible';
                if (el.disabled === true || el.getAttribute('aria-disabled') === 'true') return 'disabled';
                try { el.scrollIntoView({ block: 'center' }); } catch (e) {}
                var rr = el.getBoundingClientRect();
                var cx = Math.min(Math.max(rr.left + rr.width / 2, 1), Math.max(window.innerWidth - 1, 1));
                var cy = Math.min(Math.max(rr.top + rr.height / 2, 1), Math.max(window.innerHeight - 1, 1));
                var top = document.elementFromPoint(cx, cy);
                if (top && top !== el && !el.contains(top) && !top.contains(el)) {
                  var by = (top.tagName || '') + ' ' + (top.getAttribute('aria-label') || top.innerText || '');
                  return 'occluded ' + String(by).replace(/["\\\n\r]/g, ' ').trim().slice(0, 40);
                }
                try { el.focus(); } catch (e) {}
                el.click();
                return 'ok';
              } catch (e) {
                return 'error ' + String(e).replace(/["\\\n\r]/g, ' ').slice(0, 120);
              }
            })()
        """.trimIndent()
    }

    /**
     * Types [literal] (an already-encoded JS string literal) into an element.
     *
     * Text inputs are filled through the *prototype* value setter, because frameworks like React
     * and Vue keep their own value tracker and ignore a plain `el.value = …` assignment — that is
     * the classic "the form looks filled but submits empty" failure. `<select>` is handled by
     * matching the requested value against the options, `contenteditable` through `insertText`.
     */
    fun type(ref: String, literal: String, submit: Boolean): String {
        val safe = safeRef(ref) ?: return INVALID_REF_SCRIPT
        val submitLiteral = if (submit) "true" else "false"
        return """
            (function(){
              try {
                var el = document.querySelector('[data-agx-ref="$safe"]');
                if (!el) return 'not-found';
                if (el.disabled === true) return 'disabled';
                if (el.readOnly === true) return 'readonly';
                var r = el.getBoundingClientRect();
                if (r.width <= 0 || r.height <= 0) return 'invisible';
                try { el.scrollIntoView({ block: 'center' }); } catch (e) {}
                try { el.focus(); } catch (e) {}
                var value = $literal;
                if (el.isContentEditable) {
                  var inserted = false;
                  try { inserted = document.execCommand('insertText', false, value); } catch (e) { inserted = false; }
                  if (!inserted) { el.innerText = value; }
                  el.dispatchEvent(new Event('input', { bubbles: true }));
                  el.dispatchEvent(new Event('change', { bubbles: true }));
                } else if (el.tagName === 'SELECT') {
                  var matched = null;
                  var opts = el.options || [];
                  for (var i = 0; i < opts.length; i++) {
                    if (String(opts[i].value) === value) { matched = opts[i]; break; }
                  }
                  if (!matched) {
                    for (var j = 0; j < opts.length; j++) {
                      var exact = String(opts[j].text || '').trim().toLowerCase();
                      if (exact === value.toLowerCase()) { matched = opts[j]; break; }
                    }
                  }
                  if (!matched) {
                    for (var k = 0; k < opts.length; k++) {
                      var loose = String(opts[k].text || '').trim().toLowerCase();
                      if (loose.indexOf(value.toLowerCase()) !== -1) { matched = opts[k]; break; }
                    }
                  }
                  if (!matched) return 'option-not-found';
                  el.value = matched.value;
                  el.dispatchEvent(new Event('input', { bubbles: true }));
                  el.dispatchEvent(new Event('change', { bubbles: true }));
                } else {
                  var proto = (el.tagName === 'TEXTAREA')
                    ? window.HTMLTextAreaElement.prototype
                    : window.HTMLInputElement.prototype;
                  var desc = Object.getOwnPropertyDescriptor(proto, 'value');
                  if (desc && desc.set) { desc.set.call(el, value); } else { el.value = value; }
                  el.dispatchEvent(new Event('input', { bubbles: true }));
                  el.dispatchEvent(new Event('change', { bubbles: true }));
                }
                if ($submitLiteral) {
                  var form = el.form;
                  if (form) {
                    if (typeof form.requestSubmit === 'function') {
                      try { form.requestSubmit(); } catch (e) { form.submit(); }
                    } else {
                      form.submit();
                    }
                  } else {
                    var opts2 = { key: 'Enter', code: 'Enter', keyCode: 13, which: 13, bubbles: true };
                    el.dispatchEvent(new KeyboardEvent('keydown', opts2));
                    el.dispatchEvent(new KeyboardEvent('keyup', opts2));
                  }
                }
                return 'ok';
              } catch (e) {
                return 'error ' + String(e).replace(/["\\\n\r]/g, ' ').slice(0, 120);
              }
            })()
        """.trimIndent()
    }

    /** Chooses an option in a native `<select>` by value, exact label, then partial label. */
    fun select(ref: String, literal: String): String {
        val safe = safeRef(ref) ?: return INVALID_REF_SCRIPT
        return """
            (function(){
              try {
                var el = document.querySelector('[data-agx-ref="$safe"]');
                if (!el) return 'not-found';
                if (el.tagName !== 'SELECT') return 'not-a-select';
                if (el.disabled === true) return 'disabled';
                var want = $literal;
                var opts = el.options || [];
                var target = null;
                for (var i = 0; i < opts.length; i++) {
                  if (String(opts[i].value) === want) { target = opts[i]; break; }
                }
                if (!target) {
                  for (var j = 0; j < opts.length; j++) {
                    var exact = String(opts[j].text || '').trim().toLowerCase();
                    if (exact === want.toLowerCase()) { target = opts[j]; break; }
                  }
                }
                if (!target) {
                  for (var k = 0; k < opts.length; k++) {
                    var loose = String(opts[k].text || '').trim().toLowerCase();
                    if (loose.indexOf(want.toLowerCase()) !== -1) { target = opts[k]; break; }
                  }
                }
                if (!target) return 'option-not-found';
                try { el.focus(); } catch (e) {}
                el.value = target.value;
                el.dispatchEvent(new Event('input', { bubbles: true }));
                el.dispatchEvent(new Event('change', { bubbles: true }));
                return 'ok';
              } catch (e) {
                return 'error ' + String(e).replace(/["\\\n\r]/g, ' ').slice(0, 120);
              }
            })()
        """.trimIndent()
    }

    /**
     * Sends a single key to whatever currently has focus. This is how the agent dismisses a modal
     * (`Escape`), moves between fields (`Tab`) or submits an input that lives outside a form
     * (`Enter`), none of which the click/type scripts can express.
     */
    fun pressKey(literal: String): String = """
        (function(){
          try {
            var key = $literal;
            var opts = { key: key, code: key, bubbles: true, cancelable: true };
            var codes = {
              Enter: 13, Escape: 27, Tab: 9, Backspace: 8, Space: 32,
              ArrowUp: 38, ArrowDown: 40, ArrowLeft: 37, ArrowRight: 39
            };
            var code = codes[key];
            if (code === undefined) return 'unsupported-key';
            try { opts.keyCode = code; opts.which = code; } catch (e) {}
            var el = document.activeElement || document.body || document.documentElement;
            if (!el) return 'unsupported-key';
            el.dispatchEvent(new KeyboardEvent('keydown', opts));
            el.dispatchEvent(new KeyboardEvent('keypress', opts));
            el.dispatchEvent(new KeyboardEvent('keyup', opts));
            return 'ok';
          } catch (e) {
            return 'error ' + String(e).replace(/["\\\n\r]/g, ' ').slice(0, 120);
          }
        })()
    """.trimIndent()

    /** Scrolls the window; `amountPx` is already clamped by the tool layer. */
    fun scroll(direction: String, amountPx: Int): String = when (direction.lowercase()) {
        "up" -> "window.scrollBy(0, -$amountPx); 'ok'"
        "top" -> "window.scrollTo(0, 0); 'ok'"
        "bottom" -> "window.scrollTo(0, document.body.scrollHeight); 'ok'"
        else -> "window.scrollBy(0, $amountPx); 'ok'"
    }
}
