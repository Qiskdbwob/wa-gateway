    /**
     * Compact page fingerprint: URL, title, node count, visible-text length, a hash of every form
     * field value, open dialogs and scroll offset. Two samples that are equal mean "nothing
     * observable happened"; different samples mean the action did something. Field values are
     * included so typing into an input is detected even though the text and node count do not
     * change.
     */
    val FINGERPRINT: String = """
        (function(){
          try {
            var body = document.body;
            var text = body ? (body.innerText || '') : '';
            var fields = document.querySelectorAll('input,textarea,select');
            var acc = 0;
            for (var i = 0; i < fields.length; i++) {
              var v = String(fields[i].value == null ? '' : fields[i].value);
              var c = v.length > 0 ? v.charCodeAt(0) : 0;
              acc = (acc * 31 + v.length + c * (i + 1)) % 2147483647;
            }
            var dialogs = document.querySelectorAll('[role=dialog],dialog[open],[aria-modal=true]').length;
            var scroll = Math.round(window.scrollY || 0);
            return [
              location.href,
              document.title || '',
              document.querySelectorAll('*').length,
              text.length,
              acc,
              dialogs,
              scroll
            ].join('|');
          } catch (e) {
            return 'err';
          }
        })()
    """.trimIndent()

    /**
     * Resets a mutation counter and makes sure a `MutationObserver` is watching the document. A
     * counter (instead of a diff) keeps the settle loop cheap: one small string per poll.
     */
    val ARM_SETTLE: String = """
        (function(){
          try {
            window.__agx = window.__agx || { n: 0 };
            window.__agx.n = 0;
            if (!window.__agxObserver) {
              window.__agxObserver = new MutationObserver(function(){ window.__agx.n++; });
            }
            window.__agxObserver.observe(document.documentElement || document, {
              subtree: true, childList: true, attributes: true, characterData: true
            });
            return 'ok';
          } catch (e) {
            return 'ok';
          }
        })()
    """.trimIndent()

    /** One cheap settle sample: document readiness plus the number of DOM mutations so far. */
    val SETTLE_SAMPLE: String = """
        (function(){
          try {
            var a = window.__agx || { n: 0 };
            return document.readyState + '|' + a.n;
          } catch (e) {
            return 'unknown|0';
          }
        })()
    """.trimIndent()

    /**
     * The page snapshot: readable text plus every interactive element, each tagged with
     * `data-agx-ref` so later calls can address it. The selector covers native controls, the ARIA
     * roles real sites use, and custom widgets built from divs.
     */
    val SNAPSHOT: String = """
        (function(){
          try {
            var selector = 'a,button,input,textarea,select,summary,' +
              '[role=button],[role=link],[role=menuitem],[role=menuitemcheckbox],[role=tab],' +
              '[role=checkbox],[role=radio],[role=switch],[role=combobox],[role=option],' +
              '[role=searchbox],[role=textbox],[contenteditable=""],[contenteditable=true],' +
              '[tabindex]:not([tabindex="-1"])';
            var nodes = document.querySelectorAll(selector);
            var out = [];
            var i = 0;
            for (var k = 0; k < nodes.length && i < 80; k++) {
              var el = nodes[k];
              var r = el.getBoundingClientRect();
              if (r.width <= 0 || r.height <= 0) continue;
              var ref = 'agx-' + i;
              try { el.setAttribute('data-agx-ref', ref); } catch (e) {}
              var label = el.getAttribute('aria-label') ||
                el.getAttribute('title') ||
                el.getAttribute('alt') ||
                el.getAttribute('data-testid') ||
                el.getAttribute('placeholder') ||
                (el.innerText || el.textContent) ||
                el.value ||
                el.name ||
                el.id ||
                '';
              out.push({
                ref: ref,
                tag: (el.tagName || '').toLowerCase(),
                type: (el.getAttribute('type') || ''),
                label: ('' + label).replace(/\s+/g, ' ').trim().slice(0, 90),
                value: ('' + (el.value || '')).slice(0, 90)
              });
              i++;
            }
            return {
              url: location.href,
              title: document.title || '',
              text: (document.body ? (document.body.innerText || '') : '').slice(0, 20000),
              elements: out
            };
          } catch (e) {
            return { url: location.href, title: '', text: '', elements: [], error: '' + e };
          }
        })()
    """.trimIndent()

