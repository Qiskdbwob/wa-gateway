    private val KEY_ALIASES: Map<String, String> = mapOf(
        "enter" to "Enter", "return" to "Enter",
        "esc" to "Escape", "escape" to "Escape",
        "tab" to "Tab",
        "backspace" to "Backspace", "back" to "Backspace",
        "space" to "Space", "spasi" to "Space",
        "arrowup" to "ArrowUp", "up" to "ArrowUp", "atas" to "ArrowUp",
        "arrowdown" to "ArrowDown", "down" to "ArrowDown", "bawah" to "ArrowDown",
        "arrowleft" to "ArrowLeft", "left" to "ArrowLeft", "kiri" to "ArrowLeft",
        "arrowright" to "ArrowRight", "right" to "ArrowRight", "kanan" to "ArrowRight"
    )

    /** Keys that can be sent with [pressKey]; also the vocabulary the tool advertises. */
    val SUPPORTED_KEYS: Set<String> = KEY_ALIASES.values.toSet()

    /** Accepts `Enter`, `enter`, `esc`, `bawah`, … and returns the canonical key name, or null. */
    fun normalizeKey(key: String): String? = KEY_ALIASES[key.trim().lowercase()]

