    /**
     * Finds the element that most likely *is* [remembered] after the page re-rendered and the
     * original ref went stale. Matching is intentionally honest: an exact tag/type/label match
     * first, then an exact value match, then a label-only match — never a positional guess.
     */
    fun matchDescriptor(remembered: BrowserElement?, candidates: List<BrowserElement>): String? {
        if (remembered == null) return null
        if (remembered.label.isNotBlank()) {
            candidates.firstOrNull {
                it.tag == remembered.tag && it.type == remembered.type &&
                    it.label.equals(remembered.label, ignoreCase = true)
            }?.let { return it.ref }
        }
        if (remembered.value.isNotBlank()) {
            candidates.firstOrNull {
                it.tag == remembered.tag && it.type == remembered.type &&
                    it.value == remembered.value
            }?.let { return it.ref }
        }
        if (remembered.label.isNotBlank()) {
            candidates.firstOrNull {
                it.tag == remembered.tag && it.label.equals(remembered.label, ignoreCase = true)
            }?.let { return it.ref }
        }
        return null
    }

